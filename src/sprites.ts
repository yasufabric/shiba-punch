import { INK } from "./palette";
import { nearestScale, type Sprite } from "./pixels";

function sprite(name: string, rows: readonly string[]): Sprite {
  const width = rows[0]?.length ?? 0;
  const pixels: number[] = [];
  rows.forEach((row, y) => {
    if (row.length !== width) throw new Error(`${name} row ${y} is ${row.length}`);
    for (const ink of row) {
      const index = INK[ink];
      if (index === undefined) throw new Error(`${name} ink ${ink}`);
      pixels.push(index);
    }
  });
  return { w: width, h: rows.length, pixels };
}

